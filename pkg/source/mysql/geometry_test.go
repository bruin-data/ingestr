package mysql

import (
	"encoding/hex"
	"testing"

	"github.com/stretchr/testify/require"
)

func TestMySQLGeometryToWKT(t *testing.T) {
	// Values are HEX() of MySQL 8.4 geometry columns: SRID then WKB.
	cases := []struct {
		name string
		hex  string
		want string
	}{
		{"point", "000000000101000000000000000000F83F00000000000002C0", "POINT(1.5 -2.25)"},
		{"geographic point keeps stored longitude latitude order", "E6100000010100000000000000000034400000000000002440", "POINT(20 10)"},
		{"linestring", "110F0000010200000002000000000000000000F4BF0000000000000C4000000000006AF8408DEDB5A0F7C6B03E", "LINESTRING(-1.25 3.5,100000 0.000001)"},
		{
			"polygon with hole",
			"0000000001030000000200000005000000000000000000000000000000000000000000000000002440000000000000000000000000000024400000000000002440000000000000000000000000000024400000000000000000000000000000000004000000000000000000F03F000000000000F03F0000000000000040000000000000F03F00000000000000400000000000000040000000000000F03F000000000000F03F",
			"POLYGON((0 0,10 0,10 10,0 10,0 0),(1 1,2 1,2 2,1 1))",
		},
		{"multipoint", "000000000104000000020000000101000000000000000000000000000000000000000101000000000000000000F83F000000000000F0BF", "MULTIPOINT((0 0),(1.5 -1))"},
		{
			"multilinestring",
			"0000000001050000000200000001020000000200000000000000000000000000000000000000000000000000F03F000000000000F03F0102000000020000000000000000000040000000000000004000000000000008400000000000000840",
			"MULTILINESTRING((0 0,1 1),(2 2,3 3))",
		},
		{
			"multipolygon",
			"000000000106000000020000000103000000010000000400000000000000000000000000000000000000000000000000F03F0000000000000000000000000000F03F000000000000F03F000000000000000000000000000000000103000000010000000400000000000000000014400000000000001440000000000000184000000000000014400000000000001840000000000000184000000000000014400000000000001440",
			"MULTIPOLYGON(((0 0,1 0,1 1,0 0)),((5 5,6 5,6 6,5 5)))",
		},
		{
			"nested geometry collection",
			"000000000107000000020000000101000000000000000000F03F0000000000000040010700000001000000010200000002000000000000000000000000000000000000009A9999999999B93F48AFBC9AF2D77A3E",
			"GEOMETRYCOLLECTION(POINT(1 2),GEOMETRYCOLLECTION(LINESTRING(0 0,0.1 0.0000001)))",
		},
		{"empty geometry collection", "00000000010700000000000000", "GEOMETRYCOLLECTION EMPTY"},
		{"big-endian WKB", "00000000" + "00000000013FF80000000000004002000000000000", "POINT(1.5 2.25)"},
		{"negative zero", "000000000101000000" + "0000000000000080" + "0000000000000000", "POINT(0 0)"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			raw, err := hex.DecodeString(tc.hex)
			require.NoError(t, err)
			got, err := mysqlGeometryToWKT(raw)
			require.NoError(t, err)
			require.Equal(t, tc.want, got)
		})
	}
}

func TestMySQLGeometryToWKTRejectsMalformedValues(t *testing.T) {
	cases := []struct {
		name string
		hex  string
		want string
	}{
		{"missing SRID", "000000", "expected a 4-byte SRID"},
		{"truncated point", "000000000101000000000000000000F83F", "truncated WKB"},
		{"unknown byte order", "00000000020100000000000000000000000000000000000000", "unknown WKB byte order"},
		{"unsupported type", "000000000108000000", "unsupported WKB geometry type 8"},
		{"count exceeds payload", "000000000102000000FFFFFFFF", "truncated WKB"},
		{"wrong multi member", "0000000001040000000100000001020000000000000000", "expected a POINT member, got LINESTRING"},
		{"trailing bytes", "000000000101000000000000000000F83F00000000000002C0FF", "1 trailing bytes"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			raw, err := hex.DecodeString(tc.hex)
			require.NoError(t, err)
			_, err = mysqlGeometryToWKT(raw)
			require.ErrorContains(t, err, tc.want)
		})
	}
}
